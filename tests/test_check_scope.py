"""Checks are scoped to the step's intent and may be not-applicable only under a declared condition (ADR-0018).

The replay uses the decision recorded in a real session on 2026-11-13 (`design-options` twice: variations, then a
tweak panel). The classification is a fixture copied from that session's state, not generated by Python.
"""
import hashlib
import json
import shutil
from pathlib import Path

import pytest

from muro.core import Capability, validate_check_scope
from muro.routing import catalog_digest
from muro.runtime import Coordinator
from routing_helpers import copy_prompts, declare_prerequisite

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "examples" / "marionette"
TASK = "Bozzetto cliccabile HTML per Ethel: sistema tema x palette con pannello Tweaks"
VARIATION_CHECKS = ["options_differ_in_one_sentence", "both_ends_covered", "single_file_delivered", "recommendation_given",
                    "tweaks_update_and_persist", "panel_hidden_when_off"]
PANEL_CHECKS = ["single_file_delivered", "tweaks_update_and_persist", "panel_hidden_when_off"]


@pytest.fixture
def package(tmp_path):
    root = tmp_path / "package"
    root.mkdir()
    shutil.copytree(PACKAGE / "capabilities", root / "capabilities")
    for name in ("ROUTER.md", "sources.json", "delivery.json"):
        shutil.copy2(PACKAGE / name, root / name)
    copy_prompts(root)
    return root


def session_decision(coordinator, task=TASK):
    context = coordinator.propose(task, set())["context"]
    return {**context, "status": "selected", "selections": [
        {"step_id": "design-options#1", "capability": "design-options", "intent": "ui.design-variations",
         "reason": "Fixture from the session: the themes are variations of one screen."},
        {"step_id": "design-options#2", "capability": "design-options", "intent": "ui.tweak-controls",
         "reason": "Fixture from the session: a live panel for theme and palette on the same file."},
    ], "reason": "Fixture replay of a recorded session decision, not generated by Python.", "questions": []}


def outputs(step):
    return {"options_file": "design/bozzetti/tema-palette.html", "options_summary": f"summary of {step}"}


def passed(names):
    return [{"name": name, "status": "pass", "evidence": f"observed for {name}"} for name in names]


def start(package, tmp_path):
    coordinator = Coordinator(package, tmp_path / "consumer")
    route = session_decision(coordinator)
    proposal = coordinator.propose(TASK, set(), classification=route)
    assert proposal["mode"] == "confirm"
    return coordinator, coordinator.confirm(TASK, proposal["plan"], set(), classification=route)


def test_each_step_lists_only_the_checks_of_its_intent(package, tmp_path):
    coordinator, first = start(package, tmp_path)
    assert (first["step_id"], first["intent"]) == ("design-options#1", "ui.design-variations")
    assert first["checks"] == VARIATION_CHECKS
    assert set(first["check_conditions"]) == {"tweaks_update_and_persist", "panel_hidden_when_off"}
    na = [{"name": name, "status": "not-applicable", "evidence": "This step shows the themes side by side; the panel is step #2."}
          for name in ("tweaks_update_and_persist", "panel_hidden_when_off")]
    second = coordinator.step_atomic({"outputs": outputs("#1"), "checks": passed(VARIATION_CHECKS[:4]) + na},
                                     first["map_id"], "design-options#1")
    assert (second["step_id"], second["intent"]) == ("design-options#2", "ui.tweak-controls")
    assert second["checks"] == PANEL_CHECKS
    done = coordinator.step_atomic({"outputs": outputs("#2"), "checks": passed(PANEL_CHECKS)},
                                   second["map_id"], "design-options#2")
    assert done["mode"] == "completed"
    assert done["checks_by_capability"] == {"design-options#1": VARIATION_CHECKS, "design-options#2": PANEL_CHECKS}
    text = (tmp_path / "consumer" / ".marionette" / "map.md").read_text(encoding="utf-8")
    assert "panel_hidden_when_off (design-options#1): not-applicable" in text
    assert "options_differ_in_one_sentence (design-options#2)" not in text
    assert "recommendation_given (design-options#2)" not in text


def test_a_check_of_another_intent_is_rejected_and_nothing_is_recorded(package, tmp_path):
    coordinator, first = start(package, tmp_path)
    na = [{"name": name, "status": "not-applicable", "evidence": "No panel in this step."}
          for name in ("tweaks_update_and_persist", "panel_hidden_when_off")]
    second = coordinator.step_atomic({"outputs": outputs("#1"), "checks": passed(VARIATION_CHECKS[:4]) + na},
                                     first["map_id"], "design-options#1")
    state_path = tmp_path / "consumer" / ".marionette" / "state.json"
    before = state_path.read_text(encoding="utf-8")
    with pytest.raises(ValueError, match="does not apply to step design-options#2"):
        coordinator.step_atomic({"outputs": outputs("#2"),
                                 "checks": passed(PANEL_CHECKS + ["options_differ_in_one_sentence"])},
                                second["map_id"], "design-options#2")
    with pytest.raises(ValueError, match="does not apply to step design-options#2"):
        coordinator.record_check(passed(["recommendation_given"]), second["map_id"], "design-options#2")
    assert state_path.read_text(encoding="utf-8") == before


def test_not_applicable_needs_a_declared_condition(package, tmp_path):
    coordinator, first = start(package, tmp_path)
    claimed = passed(VARIATION_CHECKS[1:]) + [
        {"name": "options_differ_in_one_sentence", "status": "not-applicable", "evidence": "Skipped."}]
    with pytest.raises(ValueError, match="declares no condition"):
        coordinator.step_atomic({"outputs": outputs("#1"), "checks": claimed}, first["map_id"], "design-options#1")


def test_a_tampered_state_with_a_foreign_check_is_refused(package, tmp_path):
    coordinator, first = start(package, tmp_path)
    state_path = tmp_path / "consumer" / ".marionette" / "state.json"
    state = json.loads(state_path.read_text(encoding="utf-8"))
    state["results"].append({"name": "both_ends_covered", "status": "pass", "evidence": "forged",
                             "capability": "design-options#2"})
    state_path.write_text(json.dumps(state), encoding="utf-8")
    with pytest.raises(ValueError, match="Invalid state check results"):
        Coordinator(package, tmp_path / "consumer").resume()


def test_a_direct_step_lists_the_checks_of_its_intent(package, tmp_path):
    coordinator = Coordinator(package, tmp_path / "consumer")
    task = "Scrivimi offerta, azione principale e scaletta della landing, senza costruire la pagina"
    route = {**coordinator.propose(task, set())["context"], "status": "selected", "selections": [
        {"capability": "visual-direction", "intent": "ui.landing-strategy", "reason": "Fixture: strategy only."}],
        "reason": "Fixture decision, not generated by Python.", "questions": []}
    result = coordinator.propose(task, set(), classification=route)
    if result["mode"] == "confirm":
        result = coordinator.confirm(task, result["plan"], set(), classification=route)
    assert result["intent"] == "ui.landing-strategy"
    assert result["checks"] == ["single_primary_action", "proof_supported"]
    assert "check_conditions" not in result


def test_an_after_prerequisite_needs_one_check_scope(package, tmp_path):
    declare_prerequisite(package, "motion-principles", "visual-direction")
    with pytest.raises(ValueError, match="visual-direction scopes different checks per intent"):
        Coordinator(package, tmp_path / "consumer")


INTENTS = [{"id": "a.one", "description": "One.", "excludes": []}, {"id": "a.two", "description": "Two.", "excludes": []}]


@pytest.mark.parametrize("scope, conditions, expected", [
    ({}, {}, "2 intents but no intent_checks"),
    ({"a.one": ["x"]}, {}, "declares no checks for intent(s) a.two"),
    ({"a.one": ["x"], "a.two": ["y"], "a.three": ["x"]}, {}, "names unknown intent(s) a.three"),
    ({"a.one": ["x", "y"], "a.two": []}, {}, "intent_checks for a.two is empty"),
    ({"a.one": ["x", "x"], "a.two": ["y"]}, {}, "intent_checks for a.one repeats a check"),
    ({"a.one": ["x", "z"], "a.two": ["y"]}, {}, "names undeclared check(s) z"),
    ({"a.one": ["x"], "a.two": ["x"]}, {}, "check(s) y apply to no intent"),
    ({"a.one": ["x"], "a.two": ["y"]}, {"w": "When it rains."}, "check_conditions names undeclared check(s) w"),
])
def test_check_scope_shape_is_validated(scope, conditions, expected):
    errors = validate_check_scope(INTENTS, ["x", "y"], scope, conditions)
    assert any(expected in error for error in errors), errors


def test_a_single_intent_needs_no_scope_and_a_valid_scope_passes():
    assert validate_check_scope(INTENTS[:1], ["x", "y"], {}, {"y": "Only sometimes."}) == []
    assert validate_check_scope(INTENTS, ["x", "y"], {"a.one": ["x"], "a.two": ["x", "y"]}, {}) == []


def test_a_catalog_without_check_scope_keeps_its_digest(tmp_path):
    cap = Capability(id="x", role="r", when="—", after=[], outputs=["o"], checks=["ok"], body="b",
                     path=tmp_path / "x.md", intents=INTENTS[:1])
    catalog = [{"id": "x"}]
    earlier = hashlib.sha256(json.dumps({"catalog": catalog, "bodies": {"x": "b"}, "checks": {"x": ["ok"]}, "prompt": "p"},
                                        ensure_ascii=False, sort_keys=True).encode("utf-8")).hexdigest()
    assert catalog_digest(catalog, {"x": cap}, "p") == earlier
    scoped = Capability(id="x", role="r", when="—", after=[], outputs=["o"], checks=["ok"], body="b",
                        path=tmp_path / "x.md", intents=INTENTS[:1], check_conditions={"ok": "Only sometimes."})
    assert catalog_digest(catalog, {"x": scoped}, "p") != earlier


def test_every_multi_intent_capability_of_the_example_declares_its_scope():
    from muro.core import parse_capability
    for path in sorted((PACKAGE / "capabilities").glob("*.md")):
        cap = parse_capability(path)
        if len(cap.intents) > 1:
            assert set(cap.intent_checks) == {intent["id"] for intent in cap.intents}, cap.id


def test_the_guide_keeps_both_steps_of_a_repeated_capability(tmp_path):
    from muro.guide import _examples
    from muro.core import parse_router
    from muro.routing import catalog_digest, catalog_entries
    from muro.sources import parse_capabilities
    caps = {cap.id: cap for cap in parse_capabilities(PACKAGE / "capabilities")}
    rows = parse_router(PACKAGE / "ROUTER.md")
    delivery = json.loads((PACKAGE / "delivery.json").read_text(encoding="utf-8"))
    digest = catalog_digest(catalog_entries(rows, caps), caps, (ROOT / "prompts" / "classify.md").read_text(encoding="utf-8"),
                            delivery)
    example = next(item for item in _examples(PACKAGE, rows, caps, digest) if item["title"].startswith("Temi a confronto"))
    assert example["path"] == ["design-options"]
    assert [(step["step"], step["intent"]) for step in example["steps"]] == [
        ("design-options#1", "ui.design-variations"), ("design-options#2", "ui.tweak-controls")]
