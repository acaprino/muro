"""Checks are scoped to the step's intent and may be not-applicable only under a declared condition (ADR-0018).

The plan has the shape of a decision recorded in a real session on 2026-11-13: one capability twice, each step
with another intent. Here it is `manuscript-files` of the fixture package (an edit, then a conversion). The
classification is a fixture written by the test, not generated by Python.
"""
import hashlib
import json

import pytest

from muro.core import Capability, validate_check_scope
from muro.routing import catalog_digest
from muro.runtime import Coordinator
from routing_helpers import FIXTURE, ROOT, copy_fixture, declare_prerequisite

TASK = "Rename chapter-3.docx to chapter-03.docx, then convert it to EPUB"
# The two scopes share one check. Each has one check with a declared condition, and the edit has checks of its own.
EDIT_CHECKS = ["structure_read_before_edit", "edit_verified", "original_preserved"]
CONVERSION_CHECKS = ["original_preserved", "conversion_loss_reported"]
NO_STRUCTURE = [{"name": "structure_read_before_edit", "status": "not-applicable",
                 "evidence": "This step changes only the name of the file; no structure is read."}]


@pytest.fixture
def package(tmp_path):
    # The whole fixture package, manifest included: the copy runs under its own slug and its state folder is
    # `.pressroom`.
    return copy_fixture(tmp_path / "package")


def repeated_decision(coordinator, task=TASK):
    context = coordinator.propose(task, set())["context"]
    return {**context, "status": "selected", "selections": [
        {"step_id": "manuscript-files#1", "capability": "manuscript-files", "intent": "files.editing",
         "reason": "Fixture: the file gets another name, its content stays."},
        {"step_id": "manuscript-files#2", "capability": "manuscript-files", "intent": "files.conversion",
         "reason": "Fixture: the renamed file changes format, not content."},
    ], "reason": "Fixture decision written by the test, not generated by Python.", "questions": []}


def outputs(step):
    return {"file_reading": f"reading of {step}", "file_result": "manuscripts/chapter-03.epub"}


def passed(names):
    return [{"name": name, "status": "pass", "evidence": f"observed for {name}"} for name in names]


def start(package, tmp_path):
    coordinator = Coordinator(package, tmp_path / "consumer")
    route = repeated_decision(coordinator)
    proposal = coordinator.propose(TASK, set(), classification=route)
    assert proposal["mode"] == "confirm"
    return coordinator, coordinator.confirm(TASK, proposal["plan"], set(), classification=route)


def test_each_step_lists_only_the_checks_of_its_intent(package, tmp_path):
    # In this copy the edit also answers the conversion's conditioned check, so both steps answer one check
    # with a condition: the first records it not-applicable, the second pass, each under its own step.
    path = package / "capabilities" / "manuscript-files.md"
    text = path.read_text(encoding="utf-8")
    scope = '"files.editing": ["structure_read_before_edit", "edit_verified", "original_preserved"'
    assert text.count(scope) == 1
    path.write_text(text.replace(scope, scope + ', "conversion_loss_reported"'), encoding="utf-8")
    edit_checks = EDIT_CHECKS + ["conversion_loss_reported"]
    coordinator, first = start(package, tmp_path)
    assert (first["step_id"], first["intent"]) == ("manuscript-files#1", "files.editing")
    assert first["checks"] == edit_checks
    assert set(first["check_conditions"]) == {"structure_read_before_edit", "conversion_loss_reported"}
    na = NO_STRUCTURE + [{"name": "conversion_loss_reported", "status": "not-applicable",
                          "evidence": "This step renames the file; the format changes in step #2."}]
    second = coordinator.step_atomic({"outputs": outputs("#1"), "checks": passed(EDIT_CHECKS[1:]) + na},
                                     first["map_id"], "manuscript-files#1")
    assert (second["step_id"], second["intent"]) == ("manuscript-files#2", "files.conversion")
    assert second["checks"] == CONVERSION_CHECKS
    assert set(second["check_conditions"]) == {"conversion_loss_reported"}
    done = coordinator.step_atomic({"outputs": outputs("#2"), "checks": passed(CONVERSION_CHECKS)},
                                   second["map_id"], "manuscript-files#2")
    assert done["mode"] == "completed"
    assert done["checks_by_capability"] == {"manuscript-files#1": edit_checks, "manuscript-files#2": CONVERSION_CHECKS}
    text = (tmp_path / "consumer" / ".pressroom" / "map.md").read_text(encoding="utf-8")
    assert "conversion_loss_reported (manuscript-files#1): not-applicable" in text
    assert "structure_read_before_edit (manuscript-files#2)" not in text
    assert "edit_verified (manuscript-files#2)" not in text


def test_a_check_of_another_intent_is_rejected_and_nothing_is_recorded(package, tmp_path):
    coordinator, first = start(package, tmp_path)
    second = coordinator.step_atomic({"outputs": outputs("#1"), "checks": passed(EDIT_CHECKS[1:]) + NO_STRUCTURE},
                                     first["map_id"], "manuscript-files#1")
    state_path = tmp_path / "consumer" / ".pressroom" / "state.json"
    before = state_path.read_text(encoding="utf-8")
    with pytest.raises(ValueError, match="does not apply to step manuscript-files#2"):
        coordinator.step_atomic({"outputs": outputs("#2"),
                                 "checks": passed(CONVERSION_CHECKS + ["structure_read_before_edit"])},
                                second["map_id"], "manuscript-files#2")
    with pytest.raises(ValueError, match="does not apply to step manuscript-files#2"):
        coordinator.record_check(passed(["edit_verified"]), second["map_id"], "manuscript-files#2")
    assert state_path.read_text(encoding="utf-8") == before


def test_not_applicable_needs_a_declared_condition(package, tmp_path):
    coordinator, first = start(package, tmp_path)
    claimed = passed(EDIT_CHECKS[:1] + EDIT_CHECKS[2:]) + [
        {"name": "edit_verified", "status": "not-applicable", "evidence": "Skipped."}]
    with pytest.raises(ValueError, match="declares no condition"):
        coordinator.step_atomic({"outputs": outputs("#1"), "checks": claimed}, first["map_id"], "manuscript-files#1")


def test_a_tampered_state_with_a_foreign_check_is_refused(package, tmp_path):
    coordinator, first = start(package, tmp_path)
    state_path = tmp_path / "consumer" / ".pressroom" / "state.json"
    state = json.loads(state_path.read_text(encoding="utf-8"))
    state["results"].append({"name": "edit_verified", "status": "pass", "evidence": "forged",
                             "capability": "manuscript-files#2"})
    state_path.write_text(json.dumps(state), encoding="utf-8")
    with pytest.raises(ValueError, match="Invalid state check results"):
        Coordinator(package, tmp_path / "consumer").resume()


def test_a_direct_step_lists_the_checks_of_its_intent(package, tmp_path):
    coordinator = Coordinator(package, tmp_path / "consumer")
    task = "Convert chapter-3.docx to EPUB, with no change to its content"
    route = {**coordinator.propose(task, set())["context"], "status": "selected", "selections": [
        {"capability": "manuscript-files", "intent": "files.conversion", "reason": "Fixture: conversion only."}],
        "reason": "Fixture decision, not generated by Python.", "questions": []}
    result = coordinator.propose(task, set(), classification=route)
    assert result["mode"] == "direct"
    assert result["intent"] == "files.conversion"      # not the first intent of its capability
    assert result["checks"] == CONVERSION_CHECKS
    assert set(result["check_conditions"]) == {"conversion_loss_reported"}
    assert "target format" in result["check_conditions"]["conversion_loss_reported"]
    assert "edit_verified" not in result["checks"] and "structure_read_before_edit" not in result["checks"]


def test_an_after_prerequisite_needs_one_check_scope(package, tmp_path):
    declare_prerequisite(package, "pacing-spec", "story-brief")
    with pytest.raises(ValueError, match="story-brief scopes different checks per intent"):
        Coordinator(package, tmp_path / "consumer")


INTENTS = [{"id": "a.one", "description": "One.", "excludes": []}, {"id": "a.two", "description": "Two.", "excludes": []}]


@pytest.mark.parametrize("scope, conditions, expected", [
    ({}, {}, "2 intents but no intent_checks"),
    ({"a.one": ["x"]}, {}, "declares no checks for intent(s) a.two"),
    ({"a.one": ["x"], "a.two": ["y"], "a.three": ["x"]}, {}, "names unknown intent(s) a.three"),
    ({"a.one": ["x", "y"], "a.two": []}, {}, "intent_checks for a.two is empty"),
    ({"a.one": ["x", "x"], "a.two": ["y"]}, {}, "intent_checks for a.one repeats a check"),
    ({"a.one": ["x", "z"], "a.two": ["y"]}, {}, "names undeclared check(s) z"),
    ({"a.one": ["x"], "a.two": ["x"]}, {}, "check(s) y apply to no intent"),
    ({"a.one": ["x"], "a.two": ["y"]}, {"w": "When it rains."}, "check_conditions names undeclared check(s) w"),
])
def test_check_scope_shape_is_validated(scope, conditions, expected):
    errors = validate_check_scope(INTENTS, ["x", "y"], scope, conditions)
    assert any(expected in error for error in errors), errors


def test_a_single_intent_needs_no_scope_and_a_valid_scope_passes():
    assert validate_check_scope(INTENTS[:1], ["x", "y"], {}, {"y": "Only sometimes."}) == []
    assert validate_check_scope(INTENTS, ["x", "y"], {"a.one": ["x"], "a.two": ["x", "y"]}, {}) == []


def test_a_catalog_without_check_scope_keeps_its_digest(tmp_path):
    cap = Capability(id="x", role="r", when="—", after=[], outputs=["o"], checks=["ok"], body="b",
                     path=tmp_path / "x.md", intents=INTENTS[:1])
    catalog = [{"id": "x"}]
    earlier = hashlib.sha256(json.dumps({"catalog": catalog, "bodies": {"x": "b"}, "checks": {"x": ["ok"]}, "prompt": "p"},
                                        ensure_ascii=False, sort_keys=True).encode("utf-8")).hexdigest()
    assert catalog_digest(catalog, {"x": cap}, "p") == earlier
    scoped = Capability(id="x", role="r", when="—", after=[], outputs=["o"], checks=["ok"], body="b",
                        path=tmp_path / "x.md", intents=INTENTS[:1], check_conditions={"ok": "Only sometimes."})
    assert catalog_digest(catalog, {"x": scoped}, "p") != earlier


def test_the_guide_keeps_both_steps_of_a_repeated_capability(tmp_path):
    from muro.guide import _examples
    from muro.core import parse_router
    from muro.routing import catalog_digest, catalog_entries
    from muro.sources import parse_capabilities
    caps = {cap.id: cap for cap in parse_capabilities(FIXTURE / "capabilities")}
    rows = parse_router(FIXTURE / "ROUTER.md")
    delivery = json.loads((FIXTURE / "delivery.json").read_text(encoding="utf-8"))
    digest = catalog_digest(catalog_entries(rows, caps), caps, (ROOT / "prompts" / "classify.md").read_text(encoding="utf-8"),
                            delivery)
    example = next(item for item in _examples(FIXTURE, rows, caps, digest) if item["title"].startswith("Two operations"))
    assert example["path"] == ["manuscript-files"]
    assert [(step["step"], step["intent"]) for step in example["steps"]] == [
        ("manuscript-files#1", "files.extraction"), ("manuscript-files#2", "files.conversion")]
