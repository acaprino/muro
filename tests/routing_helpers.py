def response(request, ids, status="selected"):
    assert request["mode"] == "classification-required"
    catalog = {item["id"]: item for item in request["catalog"]}
    return {
        **request["context"], "status": status,
        "selections": [{"capability": name, "intent": catalog[name]["intents"][0]["id"],
                        "reason": "Fixture: this competence matches the requested outcome."} for name in ids],
        "reason": "Fixture decision supplied by the test, not generated by Python.",
        "questions": ["Which outcome do you need?"] if status == "needs_clarification" else [],
    }


def decision(coordinator, task, ids, stack=None, status="selected"):
    return response(coordinator.propose(task, stack or set()), ids, status)


def proposed(coordinator, task, ids, stack=None, new=False):
    route = decision(coordinator, task, ids, stack)
    return coordinator.propose(task, stack or set(), new=new, classification=route)
