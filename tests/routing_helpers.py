def copy_prompts(project):
    shutil.copytree(ROOT / "prompts", project / "prompts", dirs_exist_ok=True)
    # Generic documentation fixture: an explicitly unsupported task needs no
    # capability IDs and remains valid for each test's custom catalog.
    (project / "guide-examples.json").write_text(json.dumps({"examples": [{
        "title": "Unsupported fixture request", "task": "An outcome outside this test catalog",
        "stack_tokens": [], "status": "no_match", "selections": [],
        "reason": "Explicit documentation fixture; no capability is selected.", "questions": [],
    }]}), encoding="utf-8")


def declare_prerequisite(package, capability, prerequisite):
    """Fixture edge for testing prerequisite mechanics; the shipped catalog declares none."""
    path = package / "capabilities" / f"{capability}.md"
    text = path.read_text(encoding="utf-8")
    assert "\nafter: []\n" in text
    path.write_text(text.replace("\nafter: []\n", f'\nafter: ["{prerequisite}"]\n'), encoding="utf-8")
    router = package / "ROUTER.md"
    rows = router.read_text(encoding="utf-8").splitlines(keepends=True)
    prefix = f"| {capability} |"
    for index, row in enumerate(rows):
        if row.startswith(prefix):
            cells = row.split("|")
            assert cells[4].strip() == "—"
            cells[4] = f" {prerequisite} "
            rows[index] = "|".join(cells)
    router.write_text("".join(rows), encoding="utf-8")


def response(request, ids, status="selected"):
    assert request["mode"] == "classification-required"
    catalog = {item["id"]: item for item in request["catalog"] if "id" in item}   # index groups carry no id
    def judged(name):
        # Fixture judgment of conditional prerequisites: it applies exactly when the
        # test also selected the required capability. Real judgments come from the AI.
        needs = catalog[name].get("needs", [])
        return {"needs": [{"requires": need["capability"], "applies": need["capability"] in ids,
                           "reason": "Fixture judgment supplied by the test."} for need in needs]} if needs else {}
    return {
        **request["context"], "status": status,
        "selections": [{"capability": name, "intent": catalog[name]["intents"][0]["id"],
                        "reason": "Fixture: this competence matches the requested outcome.", **judged(name)} for name in ids],
        "reason": "Fixture decision supplied by the test, not generated by Python.",
        "questions": ["Which outcome do you need?"] if status == "needs_clarification" else [],
    }


def decision(coordinator, task, ids, stack=None, status="selected"):
    return response(coordinator.propose(task, stack or set()), ids, status)


def proposed(coordinator, task, ids, stack=None, new=False):
    route = decision(coordinator, task, ids, stack)
    return coordinator.propose(task, stack or set(), new=new, classification=route)
